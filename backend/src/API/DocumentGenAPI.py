@app.post("/crop_pdf")
async def crop_pdf(
    pdf_invoice_id: int = Form(...),
    x_percent: float = Form(...),
    y_percent: float = Form(...),
    width_percent: float = Form(...),
    height_percent: float = Form(...),
) -> JSON:
    """
    Crop a PDF to the specified region and update it in Strapi.

    :param pdf_invoice_id: ID of the pdf_invoice entry
    :param x_percent: Left edge of crop region as percentage (0-100)
    :param y_percent: Top edge of crop region as percentage (0-100)
    :param width_percent: Width of crop region as percentage (0-100)
    :param height_percent: Height of crop region as percentage (0-100)
    :return: Success status
    """
    import fitz  # PyMuPDF
    import tempfile

    bearer_token = os.getenv("STRAPI_BEARER_TOKEN")

    try:
        # Get the PDF from Strapi
        pdf_data = get_by_id_from_strapi(
            endpoint=STRAPI_PDFINVOICE_ENDP,
            bearer_token=bearer_token,
            entry_id=pdf_invoice_id,
            add_filter="?populate=pdf",
        )

        pdf_url = pdf_data.get("data", {}).get("attributes", {}).get("pdf", {}).get("data", {}).get("attributes", {}).get("url")
        pdf_media_id = pdf_data.get("data", {}).get("attributes", {}).get("pdf", {}).get("data", {}).get("id")

        if not pdf_url:
            return {"success": False, "error": "No PDF found for this invoice"}

        # Download the PDF
        full_url = os.getenv("STRAPI_URL") + pdf_url
        response = requests.get(full_url)
        if response.status_code != 200:
            return {"success": False, "error": "Failed to download PDF"}

        # Open PDF with PyMuPDF
        pdf_bytes = BytesIO(response.content)
        doc = fitz.open(stream=pdf_bytes, filetype="pdf")

        if len(doc) == 0:
            return {"success": False, "error": "PDF has no pages"}

        page = doc[0]
        page_rect = page.rect

        # Calculate crop box in PDF coordinates
        x = page_rect.width * (x_percent / 100)
        y = page_rect.height * (y_percent / 100)
        w = page_rect.width * (width_percent / 100)
        h = page_rect.height * (height_percent / 100)

        # Create crop rectangle
        crop_rect = fitz.Rect(x, y, x + w, y + h)

        # IMPORTANT: Actually render the cropped region to create a new PDF
        # (set_cropbox only sets metadata which pdf2image ignores)
        # Render at high resolution for quality
        zoom = 3  # 3x zoom for high quality
        mat = fitz.Matrix(zoom, zoom)
        pix = page.get_pixmap(matrix=mat, clip=crop_rect)

        # Create a new PDF with just the cropped content
        new_doc = fitz.open()
        # Create page with cropped dimensions (at 72 DPI base)
        new_page = new_doc.new_page(width=crop_rect.width, height=crop_rect.height)

        # Insert the cropped image into the new page
        img_rect = fitz.Rect(0, 0, crop_rect.width, crop_rect.height)
        new_page.insert_image(img_rect, pixmap=pix)

        # Save to temporary file
        with tempfile.NamedTemporaryFile(suffix=".pdf", delete=False) as tmp_file:
            tmp_path = tmp_file.name
            new_doc.save(tmp_path)

        new_doc.close()
        doc.close()

        # Upload the cropped PDF to Strapi media library (without ref/refId/field - we'll link manually)
        upload_url = f"{os.getenv('STRAPI_URL')}/api/upload"
        with open(tmp_path, "rb") as f:
            files = {"files": (f"cropped_{pdf_invoice_id}.pdf", f, "application/pdf")}
            upload_response = requests.post(
                upload_url,
                files=files,
                headers={"Authorization": f"Bearer {bearer_token}"}
            )

        # Clean up temp file
        os.remove(tmp_path)

        if upload_response.status_code not in [200, 201]:
            return {"success": False, "error": f"Failed to upload cropped PDF: {upload_response.text}"}

        # Extract the new file ID and URL from upload response
        upload_data = upload_response.json()
        new_file_id = None
        new_url = None
        if isinstance(upload_data, list) and len(upload_data) > 0:
            new_file_id = upload_data[0].get("id")
            new_url = upload_data[0].get("url")
        elif isinstance(upload_data, dict):
            new_file_id = upload_data.get("id")
            new_url = upload_data.get("url")

        if not new_file_id:
            return {"success": False, "error": "Failed to get new file ID from upload response"}

        print(f"[CROP DEBUG] Old PDF media ID: {pdf_media_id}")
        print(f"[CROP DEBUG] New file ID: {new_file_id}")
        print(f"[CROP DEBUG] New URL: {new_url}")

        # Explicitly update the pdf-invoice entry to link to the new file
        update_url = f"{os.getenv('STRAPI_URL')}/api/pdf-invoices/{pdf_invoice_id}"
        print(f"[CROP DEBUG] Updating pdf-invoice at: {update_url}")
        update_response = requests.put(
            update_url,
            json={"data": {"pdf": new_file_id}},
            headers={
                "Authorization": f"Bearer {bearer_token}",
                "Content-Type": "application/json"
            }
        )
        print(f"[CROP DEBUG] Update response status: {update_response.status_code}")
        print(f"[CROP DEBUG] Update response body: {update_response.text[:500]}")

        if update_response.status_code not in [200, 201]:
            return {"success": False, "error": f"Failed to update pdf-invoice relation: {update_response.text}"}

        # Verify the update worked by fetching the entry again
        verify_response = get_by_id_from_strapi(
            endpoint=STRAPI_PDFINVOICE_ENDP,
            bearer_token=bearer_token,
            entry_id=pdf_invoice_id,
            add_filter="?populate=pdf",
        )
        verify_pdf_id = verify_response.get("data", {}).get("attributes", {}).get("pdf", {}).get("data", {}).get("id")
        verify_pdf_url = verify_response.get("data", {}).get("attributes", {}).get("pdf", {}).get("data", {}).get("attributes", {}).get("url")
        print(f"[CROP DEBUG] After update - PDF ID: {verify_pdf_id}, URL: {verify_pdf_url}")

        # Delete old PDF from Strapi media library (after successful update)
        if pdf_media_id and pdf_media_id != new_file_id:
            delete_url = f"{os.getenv('STRAPI_URL')}/api/upload/files/{pdf_media_id}"
            delete_response = requests.delete(
                delete_url,
                headers={"Authorization": f"Bearer {bearer_token}"}
            )
            print(f"[CROP DEBUG] Delete old file response: {delete_response.status_code}")

        return {"success": True, "message": "PDF cropped successfully", "new_url": new_url}

    except Exception as e:
        print(f"Error cropping PDF: {str(e)}")
        return {"success": False, "error": str(e)}
