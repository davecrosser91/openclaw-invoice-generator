@app.post("/upload_logo")
async def upload_logo(
    pdf_invoice_id: int = Form(...),
    bearer_token: str = Form(...),
    file: UploadFile = File(...),
) -> JSON:
    """
    Upload a user-provided logo image and return as base64.

    :param pdf_invoice_id: ID of the pdf_invoice entry
    :param bearer_token: Strapi bearer token
    :param file: Logo image file (PNG, JPG, SVG)
    :return: Base64 data URL of the uploaded logo
    """
    import base64

    try:
        # Validate file type
        allowed_types = ["image/png", "image/jpeg", "image/jpg", "image/svg+xml"]
        if file.content_type not in allowed_types:
            return {
                "error": f"Invalid file type. Allowed: {allowed_types}",
                "success": False
            }

        # Read file content
        file_content = await file.read()

        # Convert to base64 for direct embedding in HTML
        logo_base64 = base64.b64encode(file_content).decode('utf-8')
        mime_type = file.content_type or "image/png"
        logo_data_url = f"data:{mime_type};base64,{logo_base64}"

        return {
            "success": True,
            "mediaId": 0,
            "logoUrl": logo_data_url,
            "filename": file.filename,
        }
    except Exception as e:
        print(f"Error uploading logo: {str(e)}")
        return {"error": str(e), "success": False}


