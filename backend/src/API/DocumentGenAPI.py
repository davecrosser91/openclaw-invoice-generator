@app.post("/get_pdf_from_strapi")
async def get_pdf_from_strapi(
    pdf_invoice_id: int = Form(...),
    bearer_token: str = Form(...),
    only_url: str = Form(...),
) -> JSON:
    """
    Get the pdf (as base 64 string) or the URL of a specific pdf_invoice entry (specified by the id)
    :param pdf_invoice_id: ID of the pdf_invoice entry
    :param bearer_token: Strapi bearer token
    :param only_url: If true only the url is given back. If False the  base64 string of the PDF is given back
    :return: Return either the URL or the base 64 string of the pdf, stored in Strapi within the pdf_invoice enrty with
             id: pdf_invoice_id
    """
    only_url: bool = only_url.lower() == "true"  # erzeugt true oder false aus dem string input
    response: dict = get_by_id_from_strapi(
        endpoint=STRAPI_PDFINVOICE_ENDP,
        bearer_token=bearer_token,
        entry_id=pdf_invoice_id,
        add_filter=STRAPI_ONLY_URL_OF_PDF_FILTER,
    )
    pdf_url = response["data"]["attributes"]["pdf"]["data"]["attributes"]["url"]
    if only_url:
        return {
            "url_to_pdf": os.getenv("STRAPI_URL") + pdf_url
        }  # ist ganze URL also Strapi + spezifische pdf URL
    else:
        # So weil er mich den requests.get(url=os.getenv("STRAPI_URL") + pdf_url).content nicht in den dict hat
        # schreiben lassen. Wollte immer decoden (Pydantic?).
        # UnicodeDecodeError: 'utf-8' codec can't decode byte 0xda in position 68: invalid continuation byte
        # data = Response(content=requests.get(url=os.getenv("STRAPI_URL") + pdf_url).content)
        data = requests.get(url=os.getenv("STRAPI_URL") + pdf_url).content
        pdf_base64 = base64.b64encode(data).decode("utf-8")
        return {"PDF": pdf_base64}


