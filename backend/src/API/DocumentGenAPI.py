@app.post("/import_json_invoice")
async def import_json_invoice(
    bearer_token: str = Form(...),
    json_path: str = Form(None),
    invoice_data: str = Form(None),
) -> JSON:
    """
    Import an invoice from a JSON file or JSON string directly into Strapi.
    Much faster than LLM generation - uses pre-generated invoice data.

    :param bearer_token: Strapi bearer token
    :param json_path: Path to JSON file (optional, if not provided use invoice_data)
    :param invoice_data: JSON string of invoice data (optional, if not provided use json_path)
    :return: ID of the created invoice
    """
    try:
        if json_path:
            with open(json_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
        elif invoice_data:
            data = json.loads(invoice_data)
        else:
            return {"error": "Either json_path or invoice_data must be provided"}

        adapter = Invoice_Adpater(data=data, bearer_token=bearer_token)
        created_invoice_id = adapter.post_all_available_data()
        return {"invoice_id": created_invoice_id, "status": "success"}
    except Exception as e:
        print(f"Error importing invoice: {str(e)}")
        return {"error": str(e)}


@app.get("/import_batch_invoices")
async def import_batch_invoices(
    bearer_token: str,
    folder_path: str = "gen_data/invoices_141_fixed_v4/json",
    count: int = 5,
) -> JSON:
    """
    Import multiple invoices from a folder of JSON files.

    :param bearer_token: Strapi bearer token
    :param folder_path: Path to folder containing JSON invoice files
    :param count: Number of invoices to import (default 5)
    :return: List of created invoice IDs
    """
    import glob

    try:
        # Get list of JSON files
        base_path = os.path.dirname(os.path.dirname(os.path.dirname(__file__)))
        full_path = os.path.join(base_path, folder_path)
        json_files = sorted(glob.glob(os.path.join(full_path, "invoice_*.json")))[:count]

        created_ids = []
        errors = []

        for json_file in json_files:
            try:
                with open(json_file, 'r', encoding='utf-8') as f:
                    data = json.load(f)

                adapter = Invoice_Adpater(data=data, bearer_token=bearer_token)
                invoice_id = adapter.post_all_available_data()
                created_ids.append({"file": os.path.basename(json_file), "invoice_id": invoice_id})
            except Exception as e:
                errors.append({"file": os.path.basename(json_file), "error": str(e)})

        return {
            "imported": len(created_ids),
            "invoice_ids": created_ids,
            "errors": errors if errors else None
        }
    except Exception as e:
        return {"error": str(e)}


